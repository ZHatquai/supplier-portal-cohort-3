-- Dashboard export: one row per current submission (status received), one column per question.
-- Run in the Supabase SQL editor, then Export, Download CSV. Read only: changes nothing. The seven number questions come out as numbers.
-- Includes the mock Wave 1 seed (contact emails on @example.com) until it is removed. Superseded rows are left out on purpose.
select
  s.id as submission_id, s.created_at::date as submitted_on, s.route,
  s.company_name, s.company_country, s.contact_name, s.contact_title, s.contact_email,
  s.ecovadis_link, s.declaration_name, s.declaration_date,
  max(a.response) filter (where a.question_id = 'S1-1') as s1_1,
  max(a.evidence_note) filter (where a.question_id = 'S1-1') as s1_1_note,
  max(a.response) filter (where a.question_id = 'S1-2') as s1_2,
  max(a.evidence_note) filter (where a.question_id = 'S1-2') as s1_2_note,
  max(a.response) filter (where a.question_id = 'S1-3') as s1_3,
  max(a.evidence_note) filter (where a.question_id = 'S1-3') as s1_3_note,
  max(a.response) filter (where a.question_id = 'S1-4') as s1_4,
  max(a.evidence_note) filter (where a.question_id = 'S1-4') as s1_4_note,
  (max(a.response) filter (where a.question_id = 'S2-1'))::numeric as s2_1,
  max(a.evidence_note) filter (where a.question_id = 'S2-1') as s2_1_note,
  (max(a.response) filter (where a.question_id = 'S2-2'))::numeric as s2_2,
  max(a.evidence_note) filter (where a.question_id = 'S2-2') as s2_2_note,
  (max(a.response) filter (where a.question_id = 'S2-3'))::numeric as s2_3,
  max(a.evidence_note) filter (where a.question_id = 'S2-3') as s2_3_note,
  max(a.response) filter (where a.question_id = 'S2-4') as s2_4,
  max(a.evidence_note) filter (where a.question_id = 'S2-4') as s2_4_note,
  max(a.response) filter (where a.question_id = 'S2-5') as s2_5,
  max(a.evidence_note) filter (where a.question_id = 'S2-5') as s2_5_note,
  max(a.response) filter (where a.question_id = 'S2-6') as s2_6,
  max(a.evidence_note) filter (where a.question_id = 'S2-6') as s2_6_note,
  (max(a.response) filter (where a.question_id = 'S3-1'))::numeric as s3_1,
  max(a.evidence_note) filter (where a.question_id = 'S3-1') as s3_1_note,
  max(a.response) filter (where a.question_id = 'S3-2') as s3_2,
  max(a.evidence_note) filter (where a.question_id = 'S3-2') as s3_2_note,
  max(a.response) filter (where a.question_id = 'S3-3') as s3_3,
  max(a.evidence_note) filter (where a.question_id = 'S3-3') as s3_3_note,
  max(a.response) filter (where a.question_id = 'S3-4') as s3_4,
  max(a.evidence_note) filter (where a.question_id = 'S3-4') as s3_4_note,
  (max(a.response) filter (where a.question_id = 'S4-1'))::numeric as s4_1,
  max(a.evidence_note) filter (where a.question_id = 'S4-1') as s4_1_note,
  max(a.response) filter (where a.question_id = 'S4-2') as s4_2,
  max(a.evidence_note) filter (where a.question_id = 'S4-2') as s4_2_note,
  max(a.response) filter (where a.question_id = 'S4-3') as s4_3,
  max(a.evidence_note) filter (where a.question_id = 'S4-3') as s4_3_note,
  max(a.response) filter (where a.question_id = 'S4-4') as s4_4,
  max(a.evidence_note) filter (where a.question_id = 'S4-4') as s4_4_note,
  (max(a.response) filter (where a.question_id = 'S5-1'))::numeric as s5_1,
  max(a.evidence_note) filter (where a.question_id = 'S5-1') as s5_1_note,
  (max(a.response) filter (where a.question_id = 'S5-2'))::numeric as s5_2,
  max(a.evidence_note) filter (where a.question_id = 'S5-2') as s5_2_note,
  max(a.response) filter (where a.question_id = 'S5-3') as s5_3,
  max(a.evidence_note) filter (where a.question_id = 'S5-3') as s5_3_note,
  max(a.response) filter (where a.question_id = 'S5-4') as s5_4,
  max(a.evidence_note) filter (where a.question_id = 'S5-4') as s5_4_note,
  max(a.response) filter (where a.question_id = 'S6-1') as s6_1,
  max(a.evidence_note) filter (where a.question_id = 'S6-1') as s6_1_note,
  max(a.response) filter (where a.question_id = 'S6-2') as s6_2,
  max(a.evidence_note) filter (where a.question_id = 'S6-2') as s6_2_note,
  max(a.response) filter (where a.question_id = 'S6-3') as s6_3,
  max(a.evidence_note) filter (where a.question_id = 'S6-3') as s6_3_note,
  max(a.response) filter (where a.question_id = 'S7-1') as s7_1,
  max(a.evidence_note) filter (where a.question_id = 'S7-1') as s7_1_note,
  max(a.response) filter (where a.question_id = 'S7-2') as s7_2,
  max(a.evidence_note) filter (where a.question_id = 'S7-2') as s7_2_note,
  max(a.response) filter (where a.question_id = 'S7-3') as s7_3,
  max(a.evidence_note) filter (where a.question_id = 'S7-3') as s7_3_note,
  max(a.response) filter (where a.question_id = 'S7-4') as s7_4,
  max(a.evidence_note) filter (where a.question_id = 'S7-4') as s7_4_note,
  max(a.response) filter (where a.question_id = 'S7-5') as s7_5,
  max(a.evidence_note) filter (where a.question_id = 'S7-5') as s7_5_note
from public.submissions s
left join public.submission_answers a on a.submission_id = s.id
where s.status = 'received'
group by s.id
order by s.created_at;
